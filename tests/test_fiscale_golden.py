_TOL = Decimal("0.02")


def _righe() -> list:
    righe = []
    for line in TABELLA_CSV.strip().splitlines():
        if not line.strip() or line.strip().startswith("anno;"):
            continue
        anno, ral, netto, irpef, contributi, tassazione = line.split(";")
        righe.append((int(anno), Decimal(ral), Decimal(netto), Decimal(irpef),
                      Decimal(contributi), Decimal(tassazione)))
    return righe


def _esegui(anno: int, ral: Decimal):
    regole = FakeTaxRuleService(anno)
    simulazione = SimulazioneService(
        regole,
        irpef_calc=IrpefCalculator(),
    )
    c = Contribuente(
        tipo=TipoContribuente.PersonaFisica,
        anno_riferimento=anno,
    )
    redditi = [
        Reddito(
            tipo=TipoReddito.LavoroDipendente,
            importo_lordo=ral,
            contributi_previdenziali=(ral * Decimal("0.0919")).quantize(Decimal("0.0001")),
        )
    ]
    return simulazione.esegui(c, redditi)


@pytest.mark.parametrize("riga", _righe(), ids=lambda r: f"{r[0]}-RAL{r[1]}")
def test_golden_netto(riga):
    anno, ral, netto, *_ = riga
    risultato = _esegui(anno, ral)
    assert abs(risultato.reddito_netto_stimato - netto) <= _TOL, (
        f"Netto {anno} RAL {ral}: atteso {netto}, ottenuto {risultato.reddito_netto_stimato}")


@pytest.mark.parametrize("riga", _righe(), ids=lambda r: f"{r[0]}-RAL{r[1]}")
def test_golden_irpef(riga):
    anno, ral, _, irpef, *_ = riga
    risultato = _esegui(anno, ral)
    assert abs(risultato.totale_tasse - irpef) <= _TOL, (
        f"IRPEF {anno} RAL {ral}: atteso {irpef}, ottenuto {risultato.totale_tasse}")


@pytest.mark.parametrize("riga", _righe(), ids=lambda r: f"{r[0]}-RAL{r[1]}")
def test_golden_contributi(riga):
    anno, ral, _, _, contributi, _ = riga
    risultato = _esegui(anno, ral)
    assert abs(risultato.totale_contributi_previdenziali - contributi) <= _TOL, (
        f"Contributi {anno} RAL {ral}: atteso {contributi}, "
        f"ottenuto {risultato.totale_contributi_previdenziali}")


def test_golden_invariante_netto_non_decrescente():
    for anno in (2024, 2025, 2026, 2027):
        precedente = Decimal("-1")
        for ral in (5000, 10000, 15000, 20000, 25000, 28000, 30000, 32000, 35000,
                    40000, 45000, 50000, 60000, 80000, 100000, 150000, 200000, 300000):
            risultato = _esegui(anno, Decimal(ral))
            assert risultato.reddito_netto_stimato >= precedente, (
                f"{anno} RAL {ral}: netto {risultato.reddito_netto_stimato} < precedente {precedente}")
            precedente = risultato.reddito_netto_stimato


def test_golden_regole_differenti_per_anno():
    netto2024 = _esegui(2024, Decimal(25000)).reddito_netto_stimato
    netto2025 = _esegui(2025, Decimal(25000)).reddito_netto_stimato
    netto2026 = _esegui(2026, Decimal(25000)).reddito_netto_stimato
    netto2027 = _esegui(2027, Decimal(25000)).reddito_netto_stimato
    assert netto2025 > netto2024
    assert abs(netto2025 - netto2026) <= _TOL
    assert abs(netto2026 - netto2027) <= _TOL


def test_golden_previsione_2027_nuovo_tuir():
    irpef2027 = _esegui(2027, Decimal(50000)).totale_tasse
    irpef2024 = _esegui(2024, Decimal(50000)).totale_tasse
    assert irpef2027 < irpef2024
    netto2027 = _esegui(2027, Decimal(10000)).reddito_netto_stimato
    netto2024 = _esegui(2024, Decimal(10000)).reddito_netto_stimato
    assert netto2027 > netto2024 + Decimal(100)
